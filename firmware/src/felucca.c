#endif
#ifndef FELUCCA_UART
#if BOARD_SMK37
#define FELUCCA_UART 0           /* SMK-37 Pro: TRS MIDI OUT (UART1 TX, PC7), no MIDI IN; PH8 is a key-matrix
                                  * row there and must never become UART RX. TODO: a TX driver (see the fm1-to-smk37 guide) */
#else
#define FELUCCA_UART 1           /* TRS MIDI IN on UART1 / PH8 */
#endif
#endif
#if BOARD_SMK37 && FELUCCA_UART
#error "BOARD_SMK37: midi_uart.c is the FM-1 MIDI IN driver (RX on PH8, a key-matrix row on the SMK)"
#endif
#ifndef FELUCCA_ID
#if BOARD_SMK37
#define FELUCCA_ID SMK_MODEL "_900"   /* package identity (build.py: the .fwsc marker string; SMK_MODEL: fm1_cc.h) */
#else
#define FELUCCA_ID "FM-1_900"    /* package identity (build.py: the .fwsc marker string) */
#endif
#endif
#ifndef FELUCCA_VERSION
#define FELUCCA_VERSION "v1.5.1" /* shown in the menu, the console and the editor; build.py --release X.Y */
#endif
#if FELUCCA_OTA && !FELUCCA_FLASH
#error "FELUCCA_OTA needs FELUCCA_FLASH"
#endif
#ifndef FELUCCA_USBHOST
#define FELUCCA_USBHOST BOARD_SMK37  /* USB host mode (usbhost.c): console `host`, < + > held 3 s; never at boot */
#endif
#if FELUCCA_USBHOST && !BOARD_SMK37
#error "FELUCCA_USBHOST: the SMK-37 Pro's buttons start and leave it"
#endif

