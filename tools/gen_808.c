/* Writes firmware/src/sp_808_tab.h, the constants of RHYTHM's 808 (sp_808.c): it runs FM1 Open's own float 808
 * (third_party/fm1_open/drum808.c, MIT) on the host, triggers each sound RHYTHM uses at full velocity with the
 * kit's defaults (LEVEL 100, ACCENT 127, CHOKE CH>OH; every sound's own defaults, TUNE centred) and writes what its
 * configure() computed: the filters' coefficients, the phase increments, the decays, the gains, in fixed point.
 * Only the hit's velocity changes these (in the gain, and in the kick's pitch drop: sp_808.c does both).
 *   cc -O2 -Itests/ref808 -DFM1_HOST_TEST -DFM1_OPEN_WEB -o build/gen_808 tools/gen_808.c -lm
 *   build/gen_808 > firmware/src/sp_808_tab.h */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include "../third_party/fm1_open/drum808.c"

/* RHYTHM's sounds: the part, its SOUND switch, the voice drum808.c plays it on */
enum { S_BD, S_SD, S_MT, S_MC, S_RS, S_CL, S_CP, S_CB, S_CH, S_OH, S_CY, S_N };
static const char *const NAME[S_N] = {"BD", "SD", "MT", "MC", "RS", "CL", "CP", "CB", "CH", "OH", "CY"};
static const int PART[S_N] = {D8_BD, D8_SD, D8_MT, D8_MT, D8_RS, D8_RS, D8_CP, D8_CB, D8_CH, D8_OH, D8_CY};
static const int SW[S_N] = {0, 0, 0, 1, 0, 1, 0, 0, 0, 0, 0};

static d8_voice_t *voice_of(drum808_t *d, int s)
{
    switch (s) {
    case S_BD: return &d->bd;
    case S_SD: return &d->sd;
    case S_MT: case S_MC: return &d->tom[1];
    case S_RS: return &d->rs;
    case S_CL: return &d->cl;
    case S_CP: return &d->cp;
    case S_CB: return &d->cb;
    case S_CH: return &d->ch;
    case S_OH: return &d->oh;
    default: return &d->cy;
    }
}

static long q(double x, int frac)
{
    double v = x * (double)(1L << frac);
    if (v > 2147483647.0 || v < -2147483648.0) {
        fprintf(stderr, "gen_808: %g does not fit Q%d\n", x, frac);
        exit(1);
    }
    return lround(v);
}

int main(void)
{
    static drum808_t d;
    int s, f, j;
    printf("/* SPDX-License-Identifier: MIT\n"
           " * Copyright (c) 2020 Electrosmith, Corp, Emilie Gillet; 2026 M-VAVE; 2026 M. Geisler (genkigenki/makkuro).\n"
           " * Generated by tools/gen_808.c from FM1 Open's drum808.c (third_party/fm1_open/): do not edit. */\n"
           "/* RHYTHM's 808 (sp_808.c): each sound's constants, as drum808.c's configure() makes them at full\n"
           " * velocity with the kit's defaults. svf: g, r + g, h (Q28); inc: phase increments a sample; decay, tdecay\n"
           " * (the transient), tail (Q30 a sample); tone_c (Q30); pgain (Q24); gain (Q24, x the velocity); g0, r0: the\n"
           " * kick's swept filter (tan(pi f / fs), 1 / q; Q30, Q28); attack, tone, snappy (Q30) */\n"
           "typedef struct {\n"
           "    uint32_t inc[6];\n"
           "    int32_t svf[4][3];\n"
           "    int32_t decay, tdecay, tail, tone_c, pgain, gain, g0, r0, attack, tone, snappy;\n"
           "} sp8_const_t;\n"
           "enum { S8_BD, S8_SD, S8_MT, S8_MC, S8_RS, S8_CL, S8_CP, S8_CB, S8_CH, S8_OH, S8_CY, S8_N };\n"
           "static const sp8_const_t SP8[S8_N] = {\n");
    for (s = 0; s < S_N; s++) {
        d8_voice_t *v;
        drum808_init(&d);
        if (SW[s])
            drum808_set(&d, PART[s], 3, 1);                /* (MT / RS: SOUND, the 4th parameter) */
        drum808_trigger(&d, PART[s], 1.0f);
        v = voice_of(&d, s);
        printf("    {   /* %s */\n        {", NAME[s]);
        for (j = 0; j < 6; j++)
            printf("%uu%s", (unsigned)v->increment[j], j < 5 ? ", " : "},\n        {");
        for (f = 0; f < 4; f++)
            printf("{%ld, %ld, %ld}%s", q(v->filter[f].g, 28), q(v->filter[f].r + v->filter[f].g, 28),
                   q(v->filter[f].h, 28), f < 3 ? ", " : "},\n        ");
        printf("%ld, %ld, %ld, %ld, %ld, %ld, %ld, %ld, %ld, %ld, %ld},\n",
               q(v->decay, 30), q(v->transient_decay, 30), q(v->tail_step, 30), q(v->tone_coefficient, 30),
               q(v->pulse_gain, 24), q(v->gain, 24), q(tan(3.14159265358979323846 * v->frequency / 44100.0), 30),
               q(1.0 / (v->q > .1f ? v->q : .1f), 28), q(v->attack, 30), q(v->tone, 30), q(v->snappy, 30));
    }
    printf("};\n");
    return 0;
}
